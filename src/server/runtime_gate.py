def _lock_projection_sources(db: Session, task: QueryTask) -> None:
    # Match the business delivery lock order. The selected-service dispatch
    # transaction holds these locks through the durable dispatch decision.
    evidence_documents = select(DocumentVersion.document_id).join(
        TaskEvidence, TaskEvidence.document_version_id == DocumentVersion.id
    ).where(TaskEvidence.task_id == task.id, TaskEvidence.execution_revision == task.execution_revision)
    db.scalars(select(Document.id).where(Document.id.in_(evidence_documents))
               .order_by(Document.id).with_for_update(read=True)).all()
    db.scalars(select(KnowledgeBase.id).where(KnowledgeBase.id.in_(task.effective_input["knowledge_base_ids"]))
               .order_by(KnowledgeBase.id).with_for_update(read=True)).all()


def _current_projection(db: Session, run_id: str, token: str, projection_id: str, *, for_dispatch=False):
    run, task, user, profile = _validate_run(db, run_id, token)
    if for_dispatch:
        task_write_guard(db, task)
    projection = _row(db, ModelInputProjection, projection_id)
    if (not projection or projection.run_id != run.id or _utc(projection.expires_at) <= utc_now()
            or projection.profile_configuration_hash != profile.configuration_hash):
        _deny("RUNTIME_PROJECTION_STALE", 409)
    if for_dispatch and task.input_snapshot.get("service_mode") == "selected_service":
        _lock_projection_sources(db, task)
        service = _task_service(db, task, projection.operation, profile, lock=True)
        db.scalar(select(User.id).where(User.id == task.owner_user_id).with_for_update(read=True))
        run, task, user, profile = _validate_run(db, run_id, token)
    else:
        service = _task_service(db, task, projection.operation, profile)
        if for_dispatch:
            run, task, user, profile = _validate_run(db, run_id, token)
    context, dependencies = _projection_input(db, run, task, user, profile,
                                               projection.operation, projection.business_purpose, service)
    if digest(context) != projection.context_digest or digest(canonical_json(dependencies)) != projection.dependency_digest:
        _deny("RUNTIME_PROJECTION_STALE", 409)
    return run, task, profile, projection, context, service


def _unsettled_call(db: Session, task_id: str, *, exclude: str | None = None) -> bool:
    statement = select(ModelCallAdmission.id).where(ModelCallAdmission.task_id == task_id,
        ModelCallAdmission.state.in_(("reserved", "dispatching", "streaming", "unknown")))
    if exclude is not None:
        statement = statement.where(ModelCallAdmission.id != exclude)
    return db.scalar(statement.limit(1)) is not None


def authorize_model(db: Session, run_id: str, token: str, *, projection_id: str, context_digest: str,
                    adapter: str, payload_digest: str, request_key: str) -> ModelCallAdmission:
    _, task, _, _ = _validate_run(db, run_id, token)
    task_write_guard(db, task)  # Serialize all projections before rechecking and reserving a task slot.
    run, task, profile, projection, _, _ = _current_projection(db, run_id, token, projection_id)
    if (context_digest != projection.context_digest or adapter != profile.adapter
            or not re.fullmatch(r"[0-9a-f]{64}", payload_digest) or not 1 <= len(request_key) <= 200):
        _deny("RUNTIME_ADMISSION_MISMATCH", 409)
    prior = db.scalar(select(ModelCallAdmission).where(ModelCallAdmission.run_id == run.id,
                      ModelCallAdmission.request_key == request_key).execution_options(populate_existing=True))
    if prior:
        if (prior.projection_id, prior.payload_digest, prior.context_digest, prior.adapter) != (projection.id, payload_digest, context_digest, adapter):
            _deny("RUNTIME_ADMISSION_MISMATCH", 409)
        return prior
    # One projection permits one physical request. Unsettled calls fence the whole
    # task across replacement runs and random idempotency keys.
    if _unsettled_call(db, task.id):
        _deny("RUNTIME_CALL_UNSETTLED", 409)
    if db.scalar(select(ModelCallAdmission.id).where(ModelCallAdmission.projection_id == projection.id)):
        _deny("RUNTIME_PROJECTION_CONSUMED", 409)
    if (profile.configuration["generation"].get("wire_protocol") == BAILIAN_WIRE
            and db.scalar(select(ModelCallAdmission.id).join(AgentRun, ModelCallAdmission.run_id == AgentRun.id)
                .where(ModelCallAdmission.task_id == task.id, AgentRun.execution_revision == run.execution_revision,
                       ModelCallAdmission.context_digest == context_digest, ModelCallAdmission.dispatched_at.is_not(None)).limit(1))):
        _deny("RUNTIME_PHASE_NOT_ADVANCED", 409)
    budget = _row(db, TaskBudget, task.id)
    reservation = profile.configuration["tokens_per_call"]
    changed = db.execute(update(TaskBudget).execution_options(synchronize_session=False).where(TaskBudget.task_id == task.id,
                TaskBudget.revision == budget.revision, TaskBudget.reserved_calls < TaskBudget.max_calls,
                TaskBudget.reserved_tokens + reservation <= TaskBudget.max_reserved_tokens)
                .values(reserved_calls=TaskBudget.reserved_calls + 1, reserved_tokens=TaskBudget.reserved_tokens + reservation,
                        revision=TaskBudget.revision + 1))
    if changed.rowcount != 1:
        db.rollback()
        _deny("RUNTIME_BUDGET_EXHAUSTED", 409)
    row = ModelCallAdmission(run_id=run.id, task_id=task.id, projection_id=projection.id, request_key=request_key,
                 context_digest=context_digest, payload_digest=payload_digest, adapter=adapter,
                 lease_epoch=run.lease_epoch, reserved_tokens=reservation, expires_at=projection.expires_at)
    db.add(row)
    try:
        db.commit()  # Durable intent and reservation precede permission to forward.
    except IntegrityError:
        db.rollback()
        _deny("RUNTIME_ADMISSION_CONFLICT", 409)
    return row


