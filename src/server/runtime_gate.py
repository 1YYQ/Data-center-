def _selected_model_body(context: str, generation: dict) -> dict:
    # Independently verify the pinned adapter's final request. The gateway
    # sends these same bytes, so the runtime admission and service ledger agree.
    projected = json.loads(context)
    bailian = generation.get("wire_protocol") == BAILIAN_WIRE
    options = ({**BAILIAN_OPTIONS, "max_tokens": generation["max_output_tokens"]}
               if bailian
               else {"store": False, "max_completion_tokens": generation["max_output_tokens"]})
    result = {"model": generation["model"], "stream": True,
            "stream_options": {"include_usage": True}, **options,
            "messages": [{"role": "system", "content": projected["systemPrompt"]},
                         {"role": "user", "content": projected["messages"][0]["content"]}]}
    if projected["tools"]:
        result["tools"] = [{"type": "function", "function": tool} for tool in projected["tools"]]
        if bailian:
            result["tool_choice"] = {"type": "function", "function": {"name": projected["tools"][0]["name"]}}
            result["parallel_tool_calls"] = False
    return result


def _unique_json_members(members):
    value = dict(members)
    if len(value) != len(members):
        raise ValueError("Duplicate JSON member")
    return value


def _provider_usage(raw: bytes) -> dict[str, int] | None:
    # The bounded selected response can also report usage in its trailing SSE event.
    candidates = [raw] if raw.lstrip().startswith(b"{") else (
        line[5:].strip() for line in reversed(raw.splitlines()) if line.startswith(b"data:"))
    for candidate in candidates:
        try:
            usage = _token_usage(json.loads(candidate).get("usage"), chat=True)
        except (ValueError, AttributeError):
            continue
        if usage is not None:
            return usage
    return None


def _complete_stream(raw: bytes, *, expected_model: str | None = None, expected_finish: str | None = None) -> bool:
    terminal = False
    permitted = {expected_finish} if expected_finish else {"stop", "tool_calls", "length", "content_filter"}
    frames = iter(line[5:].strip() for line in raw.splitlines() if line.startswith(b"data:"))
    for frame in frames:
        if frame == b"[DONE]":
            return terminal and next(frames, None) is None
        try:
            event = json.loads(frame)
            if expected_model is not None and event.get("model") != expected_model:
                return False
            choices = event.get("choices", [])
            terminal |= any(choice.get("finish_reason") in permitted for choice in choices)
        except (ValueError, AttributeError, TypeError):
            return False
    return False


def _bailian_stream_call(raw: bytes, model: str, expected_tool: str | None) -> dict | None:
    """Return the one authorized call, an empty dict for a text stop, or None for an invalid stream."""
    terminal = usage_tail = False
    call_id = call_name = ""
    arguments = []
    frames = iter(line[5:].strip() for line in raw.splitlines() if line.startswith(b"data:"))
    try:
        for frame in frames:
            if frame == b"[DONE]":
                if not terminal or next(frames, None) is not None:
                    return None
                if expected_tool is None:
                    return {}
                args = json.loads("".join(arguments), object_pairs_hook=_unique_json_members)
                if not call_id or call_name != expected_tool or not isinstance(args, dict):
                    return None
                return {"id": call_id, "name": call_name, "args": args}
            event = json.loads(frame, object_pairs_hook=_unique_json_members)
            choices = event.get("choices")
            if event.get("model") != model or not isinstance(choices, list):
                return None
            if not choices:
                if not terminal or usage_tail or not isinstance(event.get("usage"), dict):
                    return None
                usage_tail = True
                continue
            if terminal or len(choices) != 1:
                return None
            choice = choices[0]
            if type(choice.get("index")) is not int or choice["index"] != 0:
                return None
            delta = choice.get("delta")
            if delta is None:
                delta = {}
            if not isinstance(delta, dict) or delta.get("function_call") is not None:
                return None
            calls = delta.get("tool_calls")
            if calls is not None and not isinstance(calls, list):
                return None
            if calls:
                if len(calls) != 1 or expected_tool is None:
                    return None
                tool = calls[0]
                if (type(tool.get("index")) is not int or tool["index"] != 0
                        or tool.get("type") not in (None, "function") or tool.get("custom") is not None):
                    return None
                function = tool.get("function")
                if function is None:
                    function = {}
                identity, name, args = tool.get("id"), function.get("name"), function.get("arguments")
                if (identity is not None and (not isinstance(identity, str) or len(identity) > 200)
                        or identity and call_id and identity != call_id
                        or name not in (None, "", expected_tool)
                        or args is not None and not isinstance(args, str)):
                    return None
                call_id, call_name = call_id or identity or "", call_name or name or ""
                if args:
                    arguments.append(args)
            finish = choice.get("finish_reason")
            if finish is not None:
                if finish != ("tool_calls" if expected_tool else "stop"):
                    return None
                terminal = True
    except (ValueError, TypeError, AttributeError, RecursionError):
        return None
    return None


def dispatch_model(db: Session, run_id: str, token: str, call_id: str, payload: bytes) -> dict[str, Any]:
    from .service_use import reserve_call, settle_call

    call = _row(db, ModelCallAdmission, call_id)
    if not call or call.run_id != run_id:
        _deny("RUNTIME_CALL_NOT_FOUND", 404)
    run, task, profile, _, context, service = _current_projection(
        db, run_id, token, call.projection_id, for_dispatch=call.state == "reserved")
    call = _row(db, ModelCallAdmission, call_id)
    if digest(payload) != call.payload_digest or call.lease_epoch != run.lease_epoch:
        _deny("RUNTIME_PAYLOAD_MISMATCH", 409)
    config = profile.configuration
    contract = service[-1] if service is not None else config["generation"]
    bailian = contract.get("wire_protocol") == BAILIAN_WIRE
    upstream_path = BAILIAN_CHAT_PATH if bailian else CHAT_COMPLETIONS
    if len(payload) > config["max_payload_bytes"]:
        _deny("RUNTIME_PAYLOAD_BUDGET", 413)
    try:
        body = json.loads(payload, object_pairs_hook=_unique_json_members)
        if not isinstance(body, dict) or body.get("model") != contract["model"] or any(key in body for key in ("base_url", "url", "headers", "callback")):
            _deny("RUNTIME_PAYLOAD_MISMATCH", 409)
        caps = [key for key in ("max_completion_tokens", "max_tokens") if key in body]
        output_cap = body[caps[0]] if len(caps) == 1 else None
        if (not isinstance(output_cap, int) or isinstance(output_cap, bool)
                or not 1 <= output_cap <= config["max_output_tokens"]
                or body.get("n", 1) != 1
                or len(payload) + output_cap > call.reserved_tokens):
            _deny("RUNTIME_PAYLOAD_BUDGET", 413)
        if service is not None:
            if canonical_json(body) != canonical_json(_selected_model_body(context, contract)):
                _deny("RUNTIME_PAYLOAD_MISMATCH", 409)
            if len(payload) + output_cap > contract["context_window"]:
                _deny("RUNTIME_PAYLOAD_BUDGET", 413)
    except (ValueError, UnicodeError):
        _deny("RUNTIME_PAYLOAD_MISMATCH", 409)
    if call.state != "reserved":
        receipt = call_receipt(db, run_id, token, call.id)
        if call.state == "received":
            check_candidate(db, run_id, token, call.id)
            receipt["body"] = call.response_body
        return receipt  # Never reissue even on a known 503 or a process restart.
    if _unsettled_call(db, task.id, exclude=call.id):
        _deny("RUNTIME_CALL_UNSETTLED", 409)  # Also fence any competing reservation accepted by an older process.
    current_lease = select(AgentSessionBinding.id).where(AgentSessionBinding.id == run.session_binding_id,
                     AgentSessionBinding.lease_owner == run.id, AgentSessionBinding.lease_epoch == run.lease_epoch,
                     AgentSessionBinding.state == "in_use", AgentSessionBinding.lease_until > utc_now()).exists()
    current_run = select(AgentRun.id).where(AgentRun.id == run.id, AgentRun.state == "active").exists()
    current_step = select(TaskStep.id).where(TaskStep.id == run.step_id, TaskStep.status == "running",
                     TaskStep.lease_owner == run.id, TaskStep.lease_epoch == run.step_lease_epoch,
                     TaskStep.lease_until > utc_now()).exists()
    changed = db.execute(update(ModelCallAdmission).execution_options(synchronize_session=False).where(ModelCallAdmission.id == call.id,
               ModelCallAdmission.state == "reserved", ModelCallAdmission.expires_at > utc_now())
               .where(current_lease, current_run, current_step)
               .values(state="dispatching", dispatched_at=utc_now()))
    if changed.rowcount != 1:
        db.rollback()
        _deny("RUNTIME_ADMISSION_CONSUMED", 409)
    service_call = None
    headers = {"Content-Type": "application/json"}
    timeout = config["request_timeout_seconds"]
    if service is not None:
        pin, endpoints, *_ = service
        try:
            service_call = reserve_call(db, pin, endpoints, request_key=call.id, method="POST",
                target=upstream_path, body=payload, proof_payload=context.encode("utf-8"), authority_check=None)
        except ProviderError as error:
            db.rollback()
            _deny(error.code, 409)
    db.commit()  # CAS consumption MUST be durable before opening the connection.
    if service is None:
        connection = http.client.HTTPConnection("127.0.0.1", config["upstream_port"], timeout=timeout)
    else:
        try:
            _, _, _, _, _, current = _current_projection(db, run_id, token, call.projection_id, for_dispatch=True)
            if current is None or current[0].id != pin.id:
                _deny("RUNTIME_SERVICE_BINDING_CHANGED", 409)
            _, _, _, endpoint, credential, tls_context, _ = current
        except SafeError as error:
            db.rollback()
            call = _row(db, ModelCallAdmission, call_id)
            call.state, call.error_code = "failed", error.code
            settle_call(db, service_call, "failed", error=error.code)
            db.commit()
            raise
        headers["Authorization"] = "Bearer " + credential
        connection = endpoint.connect(timeout, tls_context)
    response_status = None
    try:
        connection.request("POST", upstream_path, body=payload, headers=headers)
        if service_call is not None:
            # Authority is held through the wire write. Release the read and
            # no-op task locks before waiting for the upstream response.
            db.rollback()
        response = connection.getresponse()
        response_status = response.status
        raw = response.read(config["max_response_bytes"] + 1)
        if len(raw) > config["max_response_bytes"]:
            raise http.client.HTTPException("response budget")
        if service_call is not None and response.length:
            raise http.client.IncompleteRead(raw, response.length)
        if service_call is not None and response.status == 200:
            media = response.getheader("Content-Type", "").split(";", 1)[0].strip().lower()
            expected_tool = body["tools"][0]["function"]["name"] if bailian and body.get("tools") else None
            complete = (_bailian_stream_call(raw, contract["model"], expected_tool) is not None
                        if bailian else _complete_stream(raw))
            if media != "text/event-stream" or not complete:
                raise http.client.HTTPException("unsettled chat stream")
        # Redirects are recorded as failure; HTTPConnection never follows them.
        call = _row(db, ModelCallAdmission, call_id)
        call.response_status, call.received_at = response.status, utc_now()
        call.state = "received" if response.status == 200 else "failed"
        call.error_code = None if response.status == 200 else "RUNTIME_UPSTREAM_REJECTED"
        call.response_body = raw.decode("utf-8") if response.status == 200 else None
        usage = None
        if response.status == 200 and service_call is not None:
            usage = _provider_usage(raw)
        elif response.status == 200:
            try:
                usage = json.loads(raw).get("usage")
            except (ValueError, AttributeError):
                pass  # Streaming responses have no invented zero usage.
        if isinstance(usage, dict) and all(isinstance(v, int) and v >= 0 for v in usage.values()):
            call.usage_state, call.usage_json = "reported", usage
        if service_call is not None:
            settle_call(db, service_call, call.state, status=response.status,
                        response_hash=digest(raw) if call.state == "received" else None,
                        error=call.error_code, usage=usage)
        db.commit()
    except (OSError, http.client.HTTPException, UnicodeError):
        db.rollback()
        call = _row(db, ModelCallAdmission, call_id)
        call.state, call.error_code, call.usage_state = "unknown", "RUNTIME_UPSTREAM_OUTCOME_UNKNOWN", "unknown"
        call.response_status = response_status
        if service_call is not None:
            settle_call(db, service_call, "unknown", status=response_status, error=call.error_code)
        db.commit()  # Reservation is intentionally retained.
    finally:
        connection.close()
    # Provider may already possess the bytes. A denial here withholds the reply;
    # it cannot claim to retract data already sent to the synthetic upstream.
    _current_projection(db, run_id, token, call.projection_id)
    receipt = call_receipt(db, run_id, token, call.id)
    if call.state == "received":
        receipt["body"] = call.response_body
    return receipt
