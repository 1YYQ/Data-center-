@dataclass(frozen=True, slots=True)
class ProjectionResult:
    """Ephemeral private projection, separate from its durable authority record.

    The complete prompt is intentionally absent from repr and ORM persistence.
    Dependencies are exposed as a detached copy so a caller cannot mutate the
    envelope or the already committed database record through this view.
    """
    id: str
    run_id: str
    context_digest: str
    operation: str
    business_purpose: str
    expires_at: datetime
    dependency_digest: str
    profile_configuration_hash: str
    generation: dict[str, Any]
    context_json: str = field(repr=False)
    _dependencies_json: str = field(repr=False)

    @property
    def dependencies(self) -> dict[str, Any]:
        return json.loads(self._dependencies_json)


def canonical_json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False)


def digest(value: bytes | str) -> str:
    return hashlib.sha256(value.encode("utf-8") if isinstance(value, str) else value).hexdigest()


def register_context_tools(tools: list[dict[str, Any]], result_builder: Callable | None = None,
                           *, scope_resolution_validator: Callable | None = None) -> None:
    """Trusted startup only. Builder returns {tool_name,state,data,evidence_ids}.

    Data is rendered as JSON text in the user input, never interpreted as message
    roles or instructions. Empty evidence_ids are only for source-free safe state
    generated by the trusted business service. Never pass arbitrary SDK history.
    """
    global _tools, _result_builder, _scope_resolution_validator, _registry_locked
    normalized = json.loads(canonical_json(tools))
    if any(set(tool) != {"name", "description", "parameters"} for tool in normalized):
        raise ValueError("Only explicit SDK tool schemas may be registered")
    if _registry_locked:
        if (normalized != _tools or result_builder is not _result_builder
                or scope_resolution_validator is not _scope_resolution_validator):
            raise RuntimeError("Runtime tool registry already locked")
        return
    _tools, _result_builder, _registry_locked = normalized, result_builder, True
    _scope_resolution_validator = scope_resolution_validator


def create_local_profile(db: Session, *, upstream_port: int | None = None, artifact_manifest_hash: str,
                         adapter_fingerprint: str, profile_id: str = "local-pi", revision: int = 1,
                         max_calls: int = 8, max_reserved_tokens: int = 65536,
                         artifact_manifest: dict | None = None,
                         generation_revision_id: str | None = None,
                         synthetic_context_window: int = 8192) -> RuntimeProfile:
    """Trusted setup for an exact loopback fixture or a generation compatibility candidate."""
    if not _registry_locked or (upstream_port is not None and not 1 <= upstream_port <= 65535):
        raise ValueError("Register tools and use an explicit synthetic loopback port for legacy dispatch")
    if not all(re.fullmatch(r"[0-9a-f]{64}", v) for v in (artifact_manifest_hash, adapter_fingerprint)):
        raise ValueError("Pinned artifact and adapter hashes required")
    if artifact_manifest is not None and (digest(canonical_json(artifact_manifest)) != artifact_manifest_hash
            or artifact_manifest.get("built_files", {}).get("dist/controlled-provider.js") != adapter_fingerprint):
        raise ValueError("Runtime artifacts must match their manifest")
    if synthetic_context_window != 8192 and (upstream_port is None or generation_revision_id is not None):
        raise ValueError("A synthetic capacity requires an explicit loopback fixture")
    model = generation_model("pi-local-synthetic", context_window=synthetic_context_window)
    generation_binding_hash = None
    if generation_revision_id is not None:
        from .service_use import selected_revision

        if upstream_port is not None or artifact_manifest is None:
            raise ValueError("A generation compatibility candidate requires attested artifacts and the selected gateway")
        endpoints = load_local_endpoints()
        service, _, _, generation_binding_hash = selected_revision(db, "query.answer", generation_revision_id, endpoints)
        model = generation_profile(service, endpoints[service.endpoint_ref], explicit=True)
    bailian = model.get("wire_protocol") == BAILIAN_WIRE
    gateway_policy = BAILIAN_GATEWAY_POLICY if bailian else GATEWAY_POLICY
    if (max_calls < 1 or max_reserved_tokens < model["context_window"]
            or bailian and (max_calls > 8 or max_reserved_tokens > max_calls * model["context_window"])):
        raise ValueError("Positive bounded budget required")
    config = {"upstream_host": "127.0.0.1", "upstream_port": upstream_port,
              "upstream_path": BAILIAN_CHAT_PATH if bailian else CHAT_COMPLETIONS, "synthetic_only": True,
              "model": model["model"], "generation": model, "generation_revision_id": generation_revision_id,
              "generation_binding_hash": generation_binding_hash,
              "max_calls": max_calls, "max_reserved_tokens": max_reserved_tokens,
              "tokens_per_call": model["context_window"],
              "max_payload_bytes": model["context_window"] - 512,
              "max_output_tokens": model["max_output_tokens"] if generation_revision_id else 512,
              "max_response_bytes": 1048576,
              "request_timeout_seconds": gateway_policy["upstream_timeout_seconds"], "purposes": ["answer"],
              "gateway_policy": gateway_policy,
              "bridge": BRIDGE_PROFILE, "settings": SESSION_SETTINGS, "resources": SESSION_RESOURCES,
              "artifact_manifest": artifact_manifest,
              "sdk_version": "1.5.2", "sdk_source_revision": SDK_SOURCE,
              "artifact_manifest_hash": artifact_manifest_hash, "adapter": ADAPTER,
              "adapter_fingerprint": adapter_fingerprint, "tool_set_hash": digest(canonical_json(_tools))}
    existing = db.get(RuntimeProfile, (profile_id, revision), populate_existing=True)
    if existing:
        if existing.configuration_hash != digest(canonical_json(config)):
            raise ValueError("Profile revision cannot be changed")
        return existing
    row = RuntimeProfile(id=profile_id, revision=revision, sdk_version="1.5.2", sdk_source_revision=SDK_SOURCE,
                         artifact_manifest_hash=artifact_manifest_hash, adapter=ADAPTER,
                         adapter_fingerprint=adapter_fingerprint, tool_set_hash=config["tool_set_hash"],
                         configuration_hash=digest(canonical_json(config)), configuration=config)
    db.add(row)
    db.commit()
    return row


def _deny(code: str = "RUNTIME_NOT_ELIGIBLE", status: int = 403):
    raise SafeError(code, "当前任务或来源不满足模型处理条件，请刷新任务状态", status)


def _task_service(db: Session, task: QueryTask, operation: str, profile: RuntimeProfile, *, lock=False):
    from .service_use import check_pin, get_task_pin

    try:
        pin = get_task_pin(db, task.id, operation)
        selected = task.input_snapshot.get("service_mode") == "selected_service"
        if selected != (pin is not None):
            _deny("RUNTIME_SERVICE_BINDING_CHANGED", 409)
        generation_revision_id = profile.configuration["generation_revision_id"]
        if pin is None:
            if generation_revision_id is not None:
                _deny("RUNTIME_SERVICE_BINDING_CHANGED", 409)
            return None
        if pin.actor_id != task.owner_user_id or pin.resource_key != "task:" + task.id:
            _deny("RUNTIME_SERVICE_BINDING_CHANGED", 409)
        if (generation_revision_id is not None and operation == "answer" and (pin.revision_id != generation_revision_id
                or pin.binding_hash != profile.configuration["generation_binding_hash"])):
            _deny("RUNTIME_SERVICE_BINDING_CHANGED", 409)
        endpoints = load_local_endpoints()
        revision, endpoint, credential, tls_context = check_pin(db, pin, endpoints, lock=lock)
        if endpoint.egress == GENERATION_EGRESS and generation_revision_id is None:
            _deny("RUNTIME_SERVICE_BINDING_CHANGED", 409)
        model = generation_profile(revision, endpoint, explicit=generation_revision_id is not None)
        if model.get("wire_protocol") == BAILIAN_WIRE and (operation != "answer"
                or endpoint.chat_path != profile.configuration["upstream_path"]):
            _deny("RUNTIME_SERVICE_BINDING_CHANGED", 409)
        if generation_revision_id is not None and operation == "answer" and model != profile.configuration["generation"]:
            _deny("RUNTIME_SERVICE_BINDING_CHANGED", 409)
        if (model["context_window"] > profile.configuration["tokens_per_call"]
                or model["max_output_tokens"] > profile.configuration["max_output_tokens"]):
            _deny("RUNTIME_SERVICE_PROTOCOL_INCOMPATIBLE", 409)
        return pin, endpoints, revision, endpoint, credential, tls_context, model
    except ProviderError as error:
        _deny(error.code, 409)


def _row(db: Session, cls, identity):
    return db.get(cls, identity, populate_existing=True) if identity else None


def _snapshot(row) -> dict[str, Any]:
    # Fingerprint every field to invalidate changes without making a second
    # store of text, identities, approval assertions, attachments or credentials.
    values = {column.name: (_utc(value).isoformat() if isinstance(value := getattr(row, column.name), datetime) else value)
              for column in row.__table__.columns}
    return {**{column.name: values[column.name] for column in row.__table__.primary_key.columns},
            "row_digest": digest(canonical_json(values))}


def _accepted_task(db: Session, task: QueryTask) -> tuple[User, dict[str, Any]]:
    user = _row(db, User, task.owner_user_id)
    scope = getattr(task, "accepted_scope", None)
    origin = _row(db, AuthSession, getattr(task, "auth_session_id", None))
    if (not user or user.status != "active" or not has_permission(user, "task.read")
            or not has_permission(user, "knowledge.query") or not scope or not origin
            or origin.user_id != user.id or getattr(task, "authorization_basis", None) != "accepted_task"
            or scope.get("actor_user_id") != user.id or scope.get("operation") != "knowledge.query"
            or scope.get("origin_session_id") != origin.id or not scope.get("accepted_at")
            or scope.get("input_hash") != digest(canonical_json(task.input_snapshot))
            or task.kind != "query" or task.status not in {"pending", "running"}):
        _deny()
    payload = getattr(task, "effective_input", None)
    if not payload or getattr(task, "execution_revision", 0) < 1:
        _deny("RUNTIME_SCOPE_REQUIRED")
    kb_ids = scope.get("knowledge_base_ids")
    if (not isinstance(kb_ids, list) or not kb_ids or not payload.get("knowledge_base_ids")
            or not set(payload["knowledge_base_ids"]) <= set(kb_ids)):
        _deny("RUNTIME_SCOPE_REQUIRED")
    for key in ("model", "level", "category", "need_class"):
        if payload.get(key) != scope.get(key):
            if (key != "model" or scope.get("model") is not None or not payload.get("model")
                    or not _scope_resolution_validator
                    or not _scope_resolution_validator(db, task, key, payload[key])):
                _deny("RUNTIME_SCOPE_CHANGED")
    # Origin session is audit evidence. Its normal expiry/logout must not revoke
    # an already accepted task; current owner/grants remain mandatory below.
    return user, payload


def _profile(db: Session, binding: AgentSessionBinding) -> RuntimeProfile:
    profile = _row(db, RuntimeProfile, (binding.runtime_profile_id, binding.runtime_profile_revision))
    if not profile or not _registry_locked:
        _deny("RUNTIME_PROFILE_REQUIRED")
    config = profile.configuration
    artifact_manifest = config.get("artifact_manifest")
    bailian = config.get("generation", {}).get("wire_protocol") == BAILIAN_WIRE
    gateway_policy = BAILIAN_GATEWAY_POLICY if bailian else GATEWAY_POLICY
    upstream_path = BAILIAN_CHAT_PATH if bailian else CHAT_COMPLETIONS
    if (profile.configuration_hash != digest(canonical_json(config)) or profile.adapter != ADAPTER
            or profile.sdk_source_revision != SDK_SOURCE or profile.sdk_version != "1.5.2"
            or profile.tool_set_hash != digest(canonical_json(_tools))
            or config.get("tool_set_hash") != profile.tool_set_hash
            or config.get("artifact_manifest_hash") != profile.artifact_manifest_hash
            or config.get("adapter_fingerprint") != profile.adapter_fingerprint
            or config.get("upstream_host") != "127.0.0.1" or config.get("synthetic_only") is not True
            or config.get("upstream_path") != upstream_path or config.get("bridge") != BRIDGE_PROFILE
            or config.get("settings") != SESSION_SETTINGS or config.get("resources") != SESSION_RESOURCES
            or config.get("gateway_policy") != gateway_policy
            or config.get("request_timeout_seconds") != gateway_policy["upstream_timeout_seconds"]
            or config.get("model") != config.get("generation", {}).get("model")
            or (artifact_manifest is not None and digest(canonical_json(artifact_manifest)) != profile.artifact_manifest_hash)):
        _deny("RUNTIME_PROFILE_CHANGED")
    return profile


def open_run(db: Session, task_id: str, *, profile_id: str = "local-pi", profile_revision: int = 1,
             lease_seconds: int = 60) -> tuple[AgentRun, str]:
    """Only trusted worker calls this; no public route mints runtime credentials."""
    if not 1 <= lease_seconds <= 300:
        raise ValueError("Bounded lease required")
    task = _row(db, QueryTask, task_id)
    if not task:
        _deny()
    user, _ = _accepted_task(db, task)
    task_write_guard(db, task, allowed_statuses=("pending", "running"))
    binding = db.scalar(select(AgentSessionBinding).where(AgentSessionBinding.task_id == task.id).execution_options(populate_existing=True))
    now, run_id, token = utc_now(), new_id(), random_token()
    if not binding:
        binding = AgentSessionBinding(task_id=task.id, owner_user_id=user.id, runtime_profile_id=profile_id,
                                      runtime_profile_revision=profile_revision, lease_epoch=0, state="ready")
        db.add(binding)
        try:
            db.flush()
        except IntegrityError:
            db.rollback()
            _deny("RUNTIME_LEASE_CONFLICT", 409)
    if (binding.owner_user_id != user.id or binding.runtime_profile_id != profile_id
            or binding.runtime_profile_revision != profile_revision or binding.state == "quarantined"
            or (binding.lease_until and _utc(binding.lease_until) > now and binding.lease_owner)):
        _deny("RUNTIME_LEASE_CONFLICT", 409)
    profile = _profile(db, binding)
    service = _task_service(db, task, "answer", profile)
    if service is None and not profile.configuration.get("upstream_port"):
        _deny("RUNTIME_PROFILE_REQUIRED")
    epoch = binding.lease_epoch
    claimed = db.execute(update(AgentSessionBinding).execution_options(synchronize_session=False).where(AgentSessionBinding.id == binding.id,
                         AgentSessionBinding.lease_epoch == epoch).values(lease_epoch=epoch + 1,
                         lease_owner=run_id, lease_until=now + timedelta(seconds=lease_seconds), state="in_use"))
    if claimed.rowcount != 1:
        db.rollback()
        _deny("RUNTIME_LEASE_CONFLICT", 409)
    step = db.scalar(select(TaskStep).where(TaskStep.task_id == task.id, TaskStep.step_key == "query")
                     .execution_options(populate_existing=True))
    if not step or step.status not in {"pending", "running"}:
        db.rollback()
        _deny("RUNTIME_STEP_REQUIRED", 409)
    step_epoch, attempt_no = step.lease_epoch, step.attempt_count + 1
    claimed_step = db.execute(update(TaskStep).execution_options(synchronize_session=False).where(TaskStep.id == step.id, TaskStep.lease_epoch == step_epoch,
                    TaskStep.status.in_(["pending", "running"]),
                    or_(TaskStep.lease_owner.is_(None), TaskStep.lease_until.is_(None), TaskStep.lease_until <= now))
                    .values(lease_owner=run_id, lease_epoch=step_epoch + 1,
                            lease_until=now + timedelta(seconds=lease_seconds), status="running", attempt_count=attempt_no))
    if claimed_step.rowcount != 1:
        db.rollback()
        _deny("RUNTIME_STEP_LEASE_CONFLICT", 409)
    attempt = TaskAttempt(step_id=step.id, attempt_no=attempt_no, status="running")
    db.add(attempt)
    db.flush()
    if not _row(db, TaskBudget, task.id):
        db.add(TaskBudget(task_id=task.id, max_calls=profile.configuration["max_calls"],
                          max_reserved_tokens=profile.configuration["max_reserved_tokens"]))
    run = AgentRun(id=run_id, session_binding_id=binding.id, task_id=task.id, owner_user_id=user.id,
                   origin_session_id=task.auth_session_id, execution_revision=task.execution_revision,
                   lease_epoch=epoch + 1, token_hash=digest(token), step_id=step.id,
                   step_lease_epoch=step_epoch + 1, attempt_id=attempt.id)
    db.add(run)
    # A replaced lease cannot use its unconsumed reservations. Requests already
    # dispatching/unknown retain their task-wide fence and full reservation.
    db.execute(update(ModelCallAdmission).execution_options(synchronize_session=False).where(ModelCallAdmission.task_id == task.id,
               ModelCallAdmission.state == "reserved")
               .values(state="failed", error_code="RUNTIME_LEASE_REPLACED"))
    db.commit()
    return run, token


def _validate_run(db: Session, run_id: str, token: str) -> tuple[AgentRun, QueryTask, User, RuntimeProfile]:
    run = _row(db, AgentRun, run_id)
    if not run or not token or not hmac.compare_digest(digest(token), run.token_hash):
        _deny("RUNTIME_AUTH_REQUIRED", 401)
    binding = _row(db, AgentSessionBinding, run.session_binding_id)
    task = _row(db, QueryTask, run.task_id)
    step = _row(db, TaskStep, run.step_id)
    attempt = _row(db, TaskAttempt, run.attempt_id)
    if (run.state != "active" or not task or not binding or binding.task_id != task.id
            or run.owner_user_id != task.owner_user_id or binding.owner_user_id != run.owner_user_id
            or binding.state != "in_use" or binding.lease_owner != run.id
            or binding.lease_epoch != run.lease_epoch or not binding.lease_until
            or _utc(binding.lease_until) <= utc_now() or task.execution_revision != run.execution_revision
            or run.origin_session_id != task.auth_session_id):
        _deny("RUNTIME_LEASE_EXPIRED", 409)
    if (not step or not attempt or step.task_id != task.id or attempt.step_id != step.id
            or attempt.attempt_no != step.attempt_count or attempt.status != "running"
            or step.status != "running" or step.lease_owner != run.id
            or step.lease_epoch != run.step_lease_epoch or not step.lease_until or _utc(step.lease_until) <= utc_now()):
        _deny("RUNTIME_STEP_LEASE_EXPIRED", 409)
    user, _ = _accepted_task(db, task)
    return run, task, user, _profile(db, binding)


def validate_run(db: Session, run_id: str, token: str) -> tuple[AgentRun, QueryTask, User, RuntimeProfile]:
    result = _validate_run(db, run_id, token)
    _task_service(db, result[1], "answer", result[3])
    return result


def renew_run(db: Session, run_id: str, token: str, *, lease_seconds: int = 60) -> None:
    run, _, _, _ = validate_run(db, run_id, token)
    if not 1 <= lease_seconds <= 300:
        raise ValueError("Bounded lease required")
    changed = db.execute(update(AgentSessionBinding).execution_options(synchronize_session=False).where(AgentSessionBinding.id == run.session_binding_id,
                         AgentSessionBinding.lease_owner == run.id, AgentSessionBinding.lease_epoch == run.lease_epoch,
                         AgentSessionBinding.lease_until > utc_now()).values(lease_until=utc_now() + timedelta(seconds=lease_seconds)))
    if changed.rowcount != 1:
        db.rollback()
        _deny("RUNTIME_LEASE_CONFLICT", 409)
    changed_step = db.execute(update(TaskStep).execution_options(synchronize_session=False).where(TaskStep.id == run.step_id,
                    TaskStep.lease_owner == run.id, TaskStep.lease_epoch == run.step_lease_epoch,
                    TaskStep.lease_until > utc_now()).values(lease_until=utc_now() + timedelta(seconds=lease_seconds)))
    if changed_step.rowcount != 1:
        db.rollback()
        _deny("RUNTIME_STEP_LEASE_CONFLICT", 409)
    db.commit()


def _owned_run(db: Session, run_id: str, token: str) -> AgentRun:
    run = _row(db, AgentRun, run_id)
    if not run or not hmac.compare_digest(digest(token), run.token_hash):
        _deny("RUNTIME_AUTH_REQUIRED", 401)
    return run


def _revoke_reserved_models(db: Session, run_id: str):
    db.execute(update(ModelCallAdmission).execution_options(synchronize_session=False).where(ModelCallAdmission.run_id == run_id,
               ModelCallAdmission.state == "reserved").values(state="failed", error_code="RUNTIME_RUN_CLOSED"))


def fence_run(db: Session, run_id: str, token: str):
    """Invalidate the child before aborting it, without prematurely releasing its step."""
    run = _owned_run(db, run_id, token)
    # Serialize with the same binding row used by the business write fence.
    db.execute(update(AgentSessionBinding).where(AgentSessionBinding.id == run.session_binding_id,
               AgentSessionBinding.lease_owner == run.id, AgentSessionBinding.lease_epoch == run.lease_epoch,
               AgentSessionBinding.state == "in_use").values(state="interrupting"))
    db.execute(update(AgentRun).where(AgentRun.id == run_id, AgentRun.state == "active")
               .values(state="interrupted", finished_at=utc_now()))
    _revoke_reserved_models(db, run_id)
    db.commit()


def close_run(db: Session, run_id: str, token: str, *, state: str = "settled") -> None:
    # Closing is allowed after cancellation/expiry. Dispatched and unknown
    # requests keep their original durable receipts.
    run = _owned_run(db, run_id, token)
    if state not in {"settled", "interrupted", "cancelled"}:
        _deny("RUNTIME_AUTH_REQUIRED", 401)
    run.state, run.finished_at = state, utc_now()
    task = _row(db, QueryTask, run.task_id)
    task_state = task.status if task else "interrupted"
    # SDK settlement does not establish business success. Only an actual task
    # result transaction can cause a step/attempt to be recorded succeeded.
    terminal = task_state in {"succeeded", "failed", "cancelled"}
    released_step = db.execute(update(TaskStep).execution_options(synchronize_session=False).where(TaskStep.id == run.step_id,
                    TaskStep.lease_owner == run.id, TaskStep.lease_epoch == run.step_lease_epoch)
                    .values(lease_owner=None, lease_until=None, lease_epoch=run.step_lease_epoch + 1,
                            status=task_state, completed_at=utc_now() if terminal else None))
    if released_step.rowcount == 1:
        attempt = _row(db, TaskAttempt, run.attempt_id)
        if attempt:
            attempt.status = task_state if task_state != "running" else "interrupted"
            attempt.finished_at = utc_now()
    _revoke_reserved_models(db, run.id)
    db.execute(update(AgentSessionBinding).execution_options(synchronize_session=False).where(AgentSessionBinding.id == run.session_binding_id,
               AgentSessionBinding.lease_owner == run.id, AgentSessionBinding.lease_epoch == run.lease_epoch)
               .values(lease_owner=None, lease_until=None, lease_epoch=run.lease_epoch + 1, state="ready"))
    db.commit()


def _assemble(db: Session, run: AgentRun, task: QueryTask, user: User, profile: RuntimeProfile,
              operation: str, business_purpose: str) -> tuple[str, dict[str, Any]]:
    if business_purpose != "answer" or operation not in {"answer", "summary", "compaction"}:
        _deny("RUNTIME_PURPOSE_DENIED")
    from .governance import publication_is_current, publication_dependency_snapshot, can_read_version
    payload, now = task.effective_input, utc_now()
    dimensions = {key: payload.get(key) for key in ("level", "category", "need_class")}
    grants = db.scalars(select(AuthorizationGrant).where(AuthorizationGrant.subject_user_id == user.id)
                        .order_by(AuthorizationGrant.id).execution_options(populate_existing=True)).all()
    grant_snapshots = [{"grant": _snapshot(grant),
                        "approval": _snapshot(approval) if (approval := _row(db, BusinessApproval, grant.approval_id)) else None}
                       for grant in grants]
    kb_snapshots = []
    for kb_id in sorted(set(payload.get("knowledge_base_ids", []))):
        kb = _row(db, KnowledgeBase, kb_id)
        if not kb or kb.status != "active":
            _deny()
        eligible = []
        for grant in grants:
            approval = _row(db, BusinessApproval, grant.approval_id)
            if (grant.operation == "knowledge.query" and grant.knowledge_base_id == kb.id
                    and grant.document_id is None and not grant.revoked_at
                    and _utc(grant.valid_from) <= now and (not grant.valid_until or _utc(grant.valid_until) > now)
                    and all(value is None or getattr(grant, key) == value for key, value in dimensions.items())
                    and approval_allows_grant(approval, grant, now)):
                eligible.append(grant.id)
        if not eligible:
            _deny()
        kb_snapshots.append(_snapshot(kb))
    evidence = db.scalars(select(TaskEvidence).where(TaskEvidence.task_id == task.id,
                          TaskEvidence.execution_revision == task.execution_revision)
                          .order_by(TaskEvidence.id).execution_options(populate_existing=True)).all()
    sources, source_snapshots, publication_snapshots = [], [], {}
    if any(not item.chunk_id and (item.chunk_set_id is not None or item.source_binding_hash is not None
           or "fragment" in (item.source_context or {})) for item in evidence):
        _deny("RUNTIME_SOURCE_CHANGED")
    if len({bool(item.chunk_id) for item in evidence}) > 1:
        _deny("RUNTIME_SOURCE_CHANGED")
    if evidence and evidence[0].chunk_id:
        from .query_evidence import validate_task_evidence_batch
        if not validate_task_evidence_batch(db, user, task, evidence):
            _deny("RUNTIME_SOURCE_CHANGED")
    for item in evidence:
        if item.chunk_id:
            from .query_evidence import child_fragment
            fragment = child_fragment(item)
            version = _row(db, DocumentVersion, item.document_version_id)
            document = _row(db, Document, version.document_id)
            from .evidence_projection import model_fragment
            sources.append(model_fragment(fragment, evidence_id=item.id))
            if version.id not in publication_snapshots:
                publication_snapshots[version.id] = {"version_id": version.id,
                    "digest": digest(canonical_json(publication_dependency_snapshot(db, version)))}
            source_snapshots.append({"evidence": _snapshot(item), "fragment": fragment,
                "version": _snapshot(version), "document": _snapshot(document),
                "publication": publication_snapshots[version.id]})
            continue
        version = _row(db, DocumentVersion, item.document_version_id)
        document = _row(db, Document, version.document_id) if version else None
        block = _row(db, ContentBlock, item.block_id)
        chunk = _row(db, ChunkSet, version.selected_chunk_set_id) if version else None
        parse = _row(db, ParseRun, chunk.parse_run_id) if chunk else None
        file = _row(db, FileObject, version.source_file_id) if version else None
        kb = _row(db, KnowledgeBase, document.knowledge_base_id) if document else None
        generation = _row(db, IndexGeneration, kb.active_generation_id) if kb else None
        if (not all((version, document, block, chunk, parse, file, kb, generation))
                or not publication_is_current(db, version, historical=False)
                or document.knowledge_base_id not in payload.get("knowledge_base_ids", [])
                or not can_read_version(db, user, version)
                or not can_read_version(db, user, version, "knowledge.query")
                or not can_access_document(db, user, document, context=dimensions)
                or not can_access_document(db, user, document, "knowledge.query", context=dimensions)
                or file.status != "available" or block.review_status != "approved"
                or parse.status != "succeeded" or chunk.status != "ready"
                or parse.document_version_id != version.id or block.parse_run_id != parse.id
                or generation.status != "ready" or generation.source_revision != kb.content_revision
                or not payload.get("model") or payload["model"] not in version.model_scope):
            _deny("RUNTIME_SOURCE_CHANGED")
        index_source = db.scalar(select(IndexSource).where(IndexSource.index_generation_id == generation.id,
                       IndexSource.document_version_id == version.id, IndexSource.parse_run_id == parse.id,
                       IndexSource.chunk_set_id == chunk.id).execution_options(populate_existing=True))
        if not index_source or not block.locator:
            _deny("RUNTIME_SOURCE_CHANGED")
        sources.append({"evidence_id": item.id, "document_version_id": version.id, "title": document.title,
                        "revision_label": version.revision_label, "model_scope": version.model_scope,
                        "text": block.text_content, "locator": block.locator})
        # Full source contents are fingerprinted, not just metadata revisions.
        source_snapshots.append({"evidence": _snapshot(item), "version": _snapshot(version),
                                 "document": _snapshot(document), "block": _snapshot(block),
                                 "chunk": _snapshot(chunk), "parse": _snapshot(parse), "file": _snapshot(file),
                                 "kb": _snapshot(kb), "index": _snapshot(generation), "index_source": _snapshot(index_source),
                                 "publication": {"version_id": version.id,
                                     "digest": digest(canonical_json(publication_dependency_snapshot(db, version)))}})
    results = _result_builder(db, task, [item.id for item in evidence]) if _result_builder else []
    allowed_evidence = {item.id for item in evidence}
    if not isinstance(results, list):
        _deny("RUNTIME_DEPENDENCY_INCOMPLETE")
    for result in results:
        if (set(result) != {"tool_name", "state", "data", "evidence_ids"}
                or not isinstance(result["evidence_ids"], list)
                or not set(result["evidence_ids"]) <= allowed_evidence
                or result["tool_name"] not in {tool["name"] for tool in _tools}):
            _deny("RUNTIME_DEPENDENCY_INCOMPLETE")
    data = {"task_input": payload, "authorized_sources": sources, "completed_tool_results": results,
            "operation": operation, "business_purpose": business_purpose}
    if evidence and evidence[0].chunk_id:
        from .answer_delivery import model_answer_context
        _, data["answer_contract"] = model_answer_context(task, evidence)
    dependencies = {"owner": _snapshot(user),
                    "task": {"id": task.id, "execution_revision": task.execution_revision,
                             "effective_input_hash": digest(canonical_json(payload)),
                             "accepted_scope_hash": digest(canonical_json(task.accepted_scope))},
                    "binding_epoch": run.lease_epoch, "step": [run.step_id, run.step_lease_epoch, run.attempt_id],
                    "profile": profile.configuration_hash,
                    "grants": grant_snapshots, "knowledge_bases": kb_snapshots,
                    "sources": source_snapshots, "tool_results_digest": digest(canonical_json(results))}
    child = bool(evidence and evidence[0].chunk_id)
    if child:
        from .auxiliary import (auxiliary_task_state, auxiliary_dependency_digest,
                                current_auxiliary_view, build_auxiliary_context)
        auxiliary_data = {**data, **auxiliary_task_state(db, task)}
        dependencies["auxiliary_base"] = auxiliary_dependency_digest(auxiliary_data, dependencies)
    if operation != "answer":
        if not child:
            _deny("AUXILIARY_SUPPORT_UNAVAILABLE", 409)
        context = build_auxiliary_context(operation, auxiliary_data)
    else:
        if child:
            views = current_auxiliary_view(db, task, auxiliary_data, dependencies, settings=db.info.get("settings"), profile=profile)
            if views:
                data["auxiliary_views"] = {purpose: {key: value for key, value in view.items() if key != "artifact_id"}
                                           for purpose, view in views.items()}
                dependencies["auxiliary_views"] = views
        bailian = profile.configuration["generation"].get("wire_protocol") == BAILIAN_WIRE
        tools = _tools
        if bailian:
            # The search and validation gates are deterministic. The model still
            # chooses and assembles the plan from the checked evidence groups.
            completed = {result["tool_name"]: result["data"] for result in results}
            if "dc_evidence_search" not in completed:
                name = "dc_evidence_search"
            elif "dc_artifacts_validate" not in completed:
                name = "dc_artifacts_validate"
            else:
                name = "dc_artifacts_deliver" if completed["dc_artifacts_validate"].get("ready") is True else None
            dependencies["bailian_tool"] = name
            tools = [tool for tool in _tools if tool["name"] == name]
            if name == "dc_artifacts_deliver":
                tool = tools[0]
                tools = [{**tool, "parameters": {**tool["parameters"], "required": ["answer_plan"]}}]
        context = {"systemPrompt": BAILIAN_SYSTEM if bailian else SYSTEM, "tools": tools,
                   "messages": [{"role": "user", "content": [{"type": "text", "text": canonical_json(data)}], "timestamp": 0}]}
    context_json = canonical_json(context)
    if len(context_json.encode()) > profile.configuration["max_payload_bytes"] - 1024:
        _deny("RUNTIME_CONTEXT_BUDGET", 413)  # Never truncate warnings or conditions.
    return context_json, dependencies


def _projection_input(db: Session, run: AgentRun, task: QueryTask, user: User, profile: RuntimeProfile,
                      operation: str, business_purpose: str, service):
    from .service_use import prove_input

    context, dependencies = _assemble(db, run, task, user, profile, operation, business_purpose)
    if service is not None:
        pin = service[0]
        contract = service[-1]
        try:
            prove_input(db, pin, context.encode("utf-8"))
        except ProviderError as error:
            _deny(error.code, 409)
        dependencies["service_use_pin"] = {"id": pin.id, "revision_id": pin.revision_id,
                                           "binding_hash": pin.binding_hash, "generation": contract}
    return context, dependencies


